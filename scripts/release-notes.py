#!/usr/bin/env python3
"""Print the GitHub Release text for a version, from CHANGELOG.md.

The text is the version's CHANGELOG section, then a fixed part about
the release files. The release workflow writes it to a file and hands
the file to the release action.

The notes used to reach the release job as a job output. GitHub drops a
job output that it thinks may contain a secret, and for v1.3.0 it
dropped the whole section, so the Release showed only the files part.
A file has no such check.

Usage: release-notes.py <version>    (no "v": 1.2.3)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = "MohammedEl-sayedAhmed/clipman"
# GitHub refuses a release body longer than this many characters.
MAX_BODY = 125_000

FILES = """\
---

## Assets

| File | Use case | Channel |
|------|----------|---------|
| `clipman_clipboard-*.whl` | `pipx install --system-site-packages clipman-clipboard` | PyPI (also auto-published) |
| `clipman_clipboard-*.tar.gz` | source build via `pip install` | PyPI (also auto-published) |
| `clipman_*.deb` | `sudo apt install ./clipman_*.deb` | Debian / Ubuntu (system) |
| `clipman-*.rpm` | `sudo dnf install ./clipman-*.rpm` | Fedora / RHEL / openSUSE (system) |
| `clipman_*.snap` | `sudo snap install --dangerous ./clipman_*.snap` | Any distro w/ snapd (also auto-published to the Snap Store: stable, candidate, beta) |
| `clipman-extension-*.zip` | upload at <https://extensions.gnome.org/upload/> or unzip into `~/.local/share/gnome-shell/extensions/` | GNOME Extensions website (manual) |
| `Source code (zip / tar.gz)` | auto-generated by GitHub | git checkout |

**Important install caveats**

- The `.deb` / `.rpm` install the daemon to `/usr/bin/clipman` and the Python module to `/usr/lib/clipman/`, but **do not** enable the GNOME Shell extension, start the daemon at login, or register the `Super+V` keybinding: those are per-user and not automated yet (#323). The README's "Finish the setup" section lists the steps for each package.

### GNOME Shell extension (manual step — EGO has no upload API)

Download `clipman-extension-TAG.zip` and upload it at <https://extensions.gnome.org/upload/>. Existing source installs pick up the new extension automatically via `install.sh`.
"""


def section(changelog, version):
    """The text under ``## [version]`` in ``changelog``, without the
    heading, or None when there is no such section or it is empty."""
    pattern = (rf"(?ms)^##\s+\[{re.escape(version)}\][^\n]*\n"
               r"(.*?)(?=^##\s+\[|\Z)")
    match = re.search(pattern, changelog)
    notes = match.group(1).strip() if match else ""
    return notes or None


def body(notes, version, limit=MAX_BODY):
    """The release text: the notes, then the files part.

    Notes too long for GitHub are cut before a subsection and end with a
    link to the full CHANGELOG at the tag.
    """
    tag = f"v{version}"
    files = "\n\n" + FILES.replace("TAG", tag)
    if len(notes) + len(files) > limit:
        more = ("\n\nThe full notes are in [CHANGELOG.md]"
                f"(https://github.com/{REPO}/blob/{tag}/CHANGELOG.md).")
        room = limit - len(files) - len(more)
        cut = notes.rfind("\n### ", 0, room)
        notes = notes[:cut if cut > 0 else room].rstrip() + more
    return notes + files


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Print the GitHub Release text for a version.")
    parser.add_argument("version", help='the version, without "v" (1.2.3)')
    args = parser.parse_args(argv)
    changelog = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    notes = section(changelog, args.version)
    if notes is None:
        print(f"::error::CHANGELOG.md has no notes for {args.version}",
              file=sys.stderr)
        return 1
    sys.stdout.write(body(notes, args.version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
